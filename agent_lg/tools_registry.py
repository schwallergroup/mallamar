def _tool_finish_campaign(summary: str, db_path: str = None, _campaign_id=None):
    """Finish the campaign by ensuring a report exists, then sending end_batch signal to hardware."""

    completion_path = None
    command_path = None
    if _campaign_id and db_path:
        identifier = hashlib.sha256(_campaign_id.encode()).hexdigest()
        completion_path = Path(db_path).parent / '.mallamar' / 'completion' / (identifier + '.json')
        command_path = completion_path.with_suffix('.commands.json')
        if completion_path.exists():
            try:
                saved = json.loads(completion_path.read_text(encoding='utf-8'))
                if saved['campaign_id'] != _campaign_id or saved['db_path'] != str(Path(db_path).resolve()):
                    raise ValueError('Completion record belongs to another campaign')
                return saved['result'] # replay the completed tool, including its original report
            except (OSError, ValueError, KeyError) as error:
                return {'abort': True, 'error': f'Unreadable completion record: {error}'}

    result = {"status": "done", "summary": summary}

    # Determine report location - prioritize campaign pool folder
    if db_path:
        # Write report in same folder as campaign pool
        db_path_obj = Path(db_path)
        report_path = db_path_obj.parent / "campaign_report.md"
    elif "OCEAN_MAILBOX_ROOT" in os.environ:
        # Fallback to mailbox root if db_path not provided
        mailbox_root = Path(os.environ["OCEAN_MAILBOX_ROOT"])
        report_path = mailbox_root / "campaign_report.md"
    else:
        # Last resort: OCEAN repo root
        report_path = HERE / "campaign_report.md"

    # Check if report already exists (written in last 5 minutes = fresh)
    report_exists = report_path.exists()
    report_fresh = False
    if report_exists:
        age_seconds = time.time() - report_path.stat().st_mtime
        report_fresh = age_seconds < 300 # 5 minutes

    # If no fresh report exists, generate a basic one from the summary
    if not report_fresh:
        print(f"[finish_campaign] No recent report found at {report_path}, generating fallback report...")

        # Generate basic report content
        report_content = f"""# Campaign Report

**Generated**: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

## Summary

{summary}

## Notes

This report was automatically generated by the `finish_campaign` tool because no explicit report was written during the campaign workflow.

For detailed analysis, please review:
- Campaign database: `{db_path or 'N/A'}`
- Log files in the `logs/` directory
- Pareto front visualizations (if generated)

---

*To generate a more comprehensive report in future campaigns, ensure the agent calls `write_report` before `finish_campaign`.*
"""

        try:
            write_result = _tool_write_report(content=report_content, out_path=str(report_path))
            result["report_generated"] = "fallback"
            result["report_path"] = write_result.get("written_to")
            print(f"[finish_campaign] Fallback report written to: {write_result.get('written_to')}")
        except Exception as e:
            result["report_error"] = str(e)
            print(f"[finish_campaign] Failed to write fallback report: {e}")
    else:
        result["report_generated"] = "already_exists"
        result["report_path"] = str(report_path)
        print(f"[finish_campaign] Using existing report at: {report_path}")

    # Send end_batch signal if OCEAN_MAILBOX_ROOT is set (real hardware mode)
    if "OCEAN_MAILBOX_ROOT" in os.environ:
        try:
            end_result = send_end_batch(reason="optimization_complete", journal_path=command_path)
            result["end_batch"] = end_result
            if end_result.get("ok"):
                result["message"] = "Campaign finished, report ensured, and END protocol completed successfully"
            else:
                result["abort"] = True
                result["message"] = f"Campaign finished, report ensured, but END protocol had issues: {end_result.get('result', {}).get('message', 'unknown')}"
        except Exception as e:
            result["abort"] = True
            result["end_batch_error"] = str(e)
            result["message"] = f"Campaign finished, report ensured, but failed to send end_batch: {e}"
    else:
        result["message"] = "Campaign finished, report ensured (no hardware connected, end_batch not sent)"

    if completion_path is not None and not result.get('abort'):
        write_json_atomic(completion_path, {'campaign_id': _campaign_id,
                          'db_path': str(Path(db_path).resolve()), 'result': result})
    return result


